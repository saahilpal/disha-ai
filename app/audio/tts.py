import io
import edge_tts
from typing import AsyncGenerator
from app.config import settings

class TextToSpeechSynthesizer:
    """
    Asynchronous Streaming Neural Speech Synthesizer using edge-tts.
    Generates natural, expressive Indian Hinglish audio with sub-250ms TTFB.
    """

    def __init__(self):
        self.default_voice = settings.TTS_VOICE or "hi-IN-SwaraNeural"

    async def stream_audio_chunks(
        self,
        text: str,
        voice: str = None
    ) -> AsyncGenerator[bytes, None]:
        """
        Streams binary MP3 audio chunks as they are generated by edge-tts.
        """
        if not text or not text.strip():
            return

        target_voice = voice or self.default_voice
        communicate = edge_tts.Communicate(text, target_voice)

        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                yield chunk["data"]

    async def synthesize_to_bytes(
        self,
        text: str,
        voice: str = None
    ) -> bytes:
        """
        Synthesizes complete audio into bytes buffer.
        """
        buffer = io.BytesIO()
        async for chunk in self.stream_audio_chunks(text, voice):
            buffer.write(chunk)
        return buffer.getvalue()

# Global singleton
tts_synthesizer = TextToSpeechSynthesizer()

